#!/usr/bin/env python3
"""Turns the Anime4K mpv user shaders in android/native/third_party/anime4k
into android/native/frontend/anime4k_shaders.h: one GLSL ES 3 fragment shader
per pass, with mpv's texture macros, plus the textures each pass reads, the
one it writes and its size.

    python3 android/tools/anime4k_to_c.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "native" / "third_party" / "anime4k"
OUTPUT = ROOT / "native" / "frontend" / "anime4k_shaders.h"
SHADERS = [  # C name, file
    ("kAnime4kM", "Anime4K_Upscale_CNN_x2_M.glsl"),
    ("kAnime4k3d", "Anime4K_3DGraphics_Upscale_x2_US.glsl"),
    ("kAnime4kGan", "Anime4K_Upscale_GAN_x2_S.glsl"),
]
MAX_BINDS = 8


def size_of(tokens):
    """WIDTH/HEIGHT are 'NAME.w' or 'NAME.w 2 *'."""
    name = tokens[0].split(".")[0]
    if len(tokens) == 1:
        return name, 1
    if len(tokens) == 3 and tokens[2] == "*":
        return name, int(tokens[1])
    raise SystemExit(f"unsupported size {tokens}")


def parse(text):
    passes, current = [], None
    for line in text.splitlines():
        match = re.match(r"^//!(\w+)\s*(.*)$", line)
        if not match:
            if current is not None:
                current["body"].append(line)
            continue
        key, value = match.group(1), match.group(2).strip()
        if key == "DESC":
            current = {"desc": value, "binds": [], "save": "MAIN", "body": []}
            passes.append(current)
        elif key == "HOOK" and value != "MAIN":
            raise SystemExit(f"unsupported hook {value}")
        elif key == "BIND":
            current["binds"].append(value)
        elif key == "SAVE":
            current["save"] = value
        elif key == "WIDTH":
            current["size"] = size_of(value.split())
        elif key == "HEIGHT" and size_of(value.split()) != current["size"]:
            raise SystemExit("width and height must scale alike")
    return passes


def glsl(binds, body):
    lines = ["#version 300 es", "precision highp float;", "precision highp int;",
             "out vec4 fragColor;", "uniform vec2 uOutput;"]
    for name in binds:
        lines += [
            f"uniform sampler2D {name}_raw;",
            f"uniform vec2 {name}_size;",
            f"#define {name}_pt (1.0 / {name}_size)",
            f"#define {name}_pos (gl_FragCoord.xy / uOutput)",
            f"#define {name}_tex(pos) texture({name}_raw, pos)",
            f"#define {name}_texOff(off) {name}_tex({name}_pos + {name}_pt * (off))",
        ]
    lines += [line for line in body if line.strip()]
    lines.append("void main() { fragColor = hook(); }")
    return "\n".join(lines) + "\n"


def c_string(text):
    return "\n".join('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"'
                     for line in text.splitlines())


def main():
    out = ["// Generated by android/tools/anime4k_to_c.py from the Anime4K mpv shaders in",
           "// android/native/third_party/anime4k (MIT, Copyright (c) 2019-2021 bloc97).",
           "// Do not edit.",
           "#pragma once", "", '#include "upscale.h"', ""]
    for c_name, file in SHADERS:
        passes = parse((SOURCE / file).read_text())
        out.append(f"// {file}")
        out.append(f"static const HookPass {c_name}Passes[] = {{")
        for p in passes:
            if len(p["binds"]) > MAX_BINDS:
                raise SystemExit(f"{p['desc']}: too many textures")
            binds = ", ".join(f'"{b}"' for b in p["binds"])
            size, scale = p["size"]
            out.append(f"  {{  // {p['desc']}")
            out.append(c_string(glsl(p["binds"], p["body"])) + ",")
            out.append(f'   {{{binds}}}, {len(p["binds"])}, "{p["save"]}", "{size}", {scale}}},')
        out.append("};")
        out.append("")
    OUTPUT.write_text("\n".join(out))
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
